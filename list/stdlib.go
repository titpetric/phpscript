// Stdlib returns everything the standard CLI runtime registers: the functions,
// the classes and their methods, and the constants.
//
// It answers from the runtime and not from a checked-in list and a build
// reports what that build actually binds. What it cannot report is the doc
// comment written next to each registration, or the PHP spelling of a
// parameter name: a generator reads both out of the Go source, which a shipped
// binary does not carry. Those live in docs/reference/extensions/implemented-apis.md,
// generated by the same reflection plus a source scan.
func Stdlib() []Symbol {
	rt := stdlibRuntime()
	funcs, classes := apidoc.Reflect(rt)

	symbols := make([]Symbol, 0, len(funcs)+len(classes)+len(rt.DefinedConstants()))
	for _, f := range funcs {
		symbols = append(symbols, Symbol{
			Kind:      "function",
			Name:      f.Name,
			Signature: f.Name + "(" + paramTypes(f.Params) + "): " + f.Returns,
		})
	}
	// The class rows come from DeclaredClasses and not from the reflected
	// constructors, because the two do not answer the same question. A script
	// can write new stdClass(), which has no Go constructor to reflect, and a
	// name that shares its constructor with others is still a name a script
	// types. The listing then agrees with the count the `info` command
	// reports.
	byName := map[string]apidoc.Class{}
	for _, c := range classes {
		for _, name := range append([]string{c.Name}, c.Aliases...) {
			byName[name] = c
		}
		for _, m := range c.Methods {
			symbols = append(symbols, Symbol{
				Kind:      "method",
				Name:      c.Name + "::" + m.Name,
				Signature: c.Name + "::" + m.Name + "(" + paramTypes(m.Params) + "): " + m.Returns,
			})
		}
	}
	for _, name := range rt.DeclaredClasses() {
		c, ok := byName[name]
		if !ok {
			symbols = append(symbols, Symbol{Kind: "class", Name: name, Signature: "new " + name + "()"})
			continue
		}
		symbols = append(symbols, Symbol{
			Kind:      "class",
			Name:      name,
			Signature: "new " + name + "(" + paramTypes(c.Params) + ")",
		})
	}
	for name, value := range rt.DefinedConstants() {
		symbols = append(symbols, Symbol{Kind: "constant", Name: name, Signature: constantValue(value)})
	}

	sort.Slice(symbols, func(i, j int) bool {
		if symbols[i].Kind != symbols[j].Kind {
			return symbols[i].Kind < symbols[j].Kind
		}
		return symbols[i].Name < symbols[j].Name
	})
	return symbols
}

// StdlibClasses answers the named registered classes, and with no name every
// class a script can construct, each entry under the name asked about.
//
// The structure comes from reflection over the live runtime, which is what
// this build binds. The prose and the PHP spelling of a parameter name come
// from the index the binary embeds, because a shipped binary carries no Go
// source to scan.
func StdlibClasses(names ...string) ([]apidoc.Class, error) {
	rt := stdlibRuntime()
	_, classes := apidoc.Reflect(rt)
	apidoc.Embedded().Apply(classes)

	byName := map[string]apidoc.Class{}
	for _, c := range classes {
		for _, name := range append([]string{c.Name}, c.Aliases...) {
			byName[name] = c
		}
	}
	if len(names) == 0 {
		names = constructedClasses(rt, byName)
	}

	out := make([]apidoc.Class, 0, len(names))
	for _, name := range names {
		c, ok := byName[name]
		if !ok {
			// stdClass is the declared class with no Go constructor: a
			// script writes new stdClass() and there is no bound type to
			// report properties, methods or a citation for.
			return nil, fmt.Errorf("%s: not a class with a Go constructor to describe", name)
		}
		out = append(out, c.Rename(name))
	}
	return out, nil
}

// StdlibDefinitions renders the named registered classes as PHP class
// definitions, and with no name every class a script can construct.
func StdlibDefinitions(names ...string) (string, error) {
	classes, err := StdlibClasses(names...)
	if err != nil {
		return "", err
	}

	defs := make([]string, 0, len(classes))
	for _, c := range classes {
		defs = append(defs, c.PHP())
	}
	return strings.Join(defs, "\n"), nil
}

// constructedClasses names every declared class a constructor builds, in name
// order. A name sharing its constructor with others is still a name a script
// types and it gets its own definition.
func constructedClasses(rt *runner.Runtime, byName map[string]apidoc.Class) []string {
	names := make([]string, 0, len(byName))
	for _, name := range rt.DeclaredClasses() {
		if _, ok := byName[name]; ok {
			names = append(names, name)
		}
	}
	sort.Strings(names)
	return names
}

// StdlibMarkdown renders the registered surface as a markdown table, the same
// shape Markdown uses for a source listing.
func StdlibMarkdown(symbols []Symbol) string {
	rows := make([][]string, 0, len(symbols))
	for _, s := range symbols {
		rows = append(rows, []string{s.Kind, s.Name, cell(s.Signature)})
	}
	return markdownTable([]string{"Kind", "Name", "Signature"}, rows)
}

// stdlibRuntime builds the runtime the phpscript CLI runs and the listing is
// what a script sees. The request-aware functions (header, http_response_code,
// getallheaders) arrive per request and not through stdlib.Register, and a
// server-targeted script still names them and an empty request context
// registers them for the listing. This is the recipe scripts/list-apis uses.
func stdlibRuntime() *runner.Runtime {
	rt := runner.New(io.Discard, runner.Options{SAPI: "cli", RootFS: os.DirFS(".")})
	stdlib.Register(rt)
	stdlib.RegisterFS(rt, ".")
	runner.NewContext().Register(rt)
	return rt
}

// paramTypes renders a parameter list as types alone.
//
// Reflection invents a name out of the Go type and a binding with two string
// parameters publishes them as $string1 and $string2 here whatever the
// registration site called them. Printing an
// invented name is worse than printing none: it reads as the argument's real
// spelling, which only the source scan behind implemented-apis.md knows. A
// by-reference slot has no type to print and keeps its ampersand.
func paramTypes(params []apidoc.Param) string {
	parts := make([]string, 0, len(params))
	for _, p := range params {
		switch {
		case p.ByRef:
			parts = append(parts, "&$"+p.Name)
		case p.Variadic:
			parts = append(parts, p.Type+" ...")
		default:
			parts = append(parts, p.Type)
		}
	}
	return strings.Join(parts, ", ")
}

// constantValue renders a constant's value the way a script would write it.
// Only the scalar shapes occur; anything else prints as its Go rendering, and
// this guesses at nothing.
func constantValue(value any) string {
	switch v := value.(type) {
	case string:
		// Quoted and never concatenated: PHP_EOL is a newline, and a raw one
		// would break the row holding it.
		return strconv.Quote(v)
	case bool:
		if v {
			return "true"
		}
		return "false"
	case nil:
		return "null"
	}
	return fmt.Sprint(value)
}
