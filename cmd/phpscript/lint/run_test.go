func TestRunPrintsMarkdownResultsAndSummary(t *testing.T) {
	dir := t.TempDir()
	writeLintFile(t, dir, "fail.php", `<?php class Foo {`)
	writeLintFile(t, dir, "pass.php", `<?php echo "ok";`)
	writeLintFile(t, dir, "warn.php", `<?php if ($value = true) {}`)

	var out bytes.Buffer
	err := run(Options{}, []string{dir}, &out)
	if err == nil {
		t.Fatal("run returned nil error with a failing file")
	}

	got := collapse(out.String())
	for _, want := range []string{
		"## " + filepath.ToSlash(dir),
		"| Status | " + filepath.ToSlash(dir) + " | Line | Message |",
		"| FAIL | fail.php | 1 | parse error:",
		"| PASS | pass.php | | No lint findings |",
		"| WARN | warn.php | 1 | assignment in conditional statement |",
		filepath.ToSlash(dir) + ": 1 passing, 1 warnings, 1 failing",
		"Passing 1, with 1 warnings, 1 failing",
	} {
		if !strings.Contains(got, want) {
			t.Errorf("output does not contain %q:\n%s", want, out.String())
		}
	}
}

// TestRunGroupsResultsByFolder checks the per-folder layout: each folder gets
// a table of its own headed by the folder, closed by its own summary line,
// with the run's total after the last one.
func TestRunGroupsResultsByFolder(t *testing.T) {
	dir := t.TempDir()
	writeLintFile(t, dir, "pass.php", `<?php echo "ok";`)
	writeLintFile(t, filepath.Join(dir, "sub"), "warn.php", `<?php if ($value = true) {}`)

	var out bytes.Buffer
	if err := run(Options{}, []string{dir, filepath.Join(dir, "sub")}, &out); err != nil {
		t.Fatalf("run returned an error: %v", err)
	}

	got := collapse(out.String())
	top, sub := filepath.ToSlash(dir), filepath.ToSlash(filepath.Join(dir, "sub"))
	for _, want := range []string{
		"| Status | " + top + " | Line | Message |",
		"| Status | " + sub + " | Line | Message |",
		top + ": 1 passing, 0 warnings, 0 failing",
		sub + ": 0 passing, 1 warnings, 0 failing",
		"Passing 1, with 1 warnings, 0 failing",
	} {
		if !strings.Contains(got, want) {
			t.Errorf("output does not contain %q:\n%s", want, out.String())
		}
	}
	if strings.Index(got, top+":") > strings.Index(got, sub+":") {
		t.Errorf("folders are not reported in discovery order:\n%s", out.String())
	}
}

func TestRunFlatstackUsesOneResultPerFile(t *testing.T) {
	dir := t.TempDir()
	writeLintFile(t, dir, "pass.php", `<?php echo "ok";`)
	writeLintFile(t, dir, "warn.php", `<?php if ($value = true) {}`)

	var out bytes.Buffer
	if err := run(Options{Flatstack: true}, []string{dir}, &out); err != nil {
		t.Fatalf("run returned an error: %v", err)
	}

	got := out.String()
	if strings.Count(got, "| PASS ") != 1 {
		t.Errorf("got duplicate or missing passing rows:\n%s", got)
	}
	if !strings.Contains(got, "[flatstack compatible]") {
		t.Errorf("flatstack passing result is missing:\n%s", got)
	}
	if !strings.Contains(got, "Passing 1, with 1 warnings, 0 failing") {
		t.Errorf("unexpected summary:\n%s", got)
	}
}

// TestRunWritesMarkdownReport checks the -o file against the markdown that a
// redirected stdout produces: the report is the same table plus a header, so
// one run can print to a terminal and record the findings at once.
func TestRunWritesMarkdownReport(t *testing.T) {
	dir := t.TempDir()
	writeLintFile(t, dir, "warn.php", `<?php if ($value = true) {}`)
	output := filepath.Join(dir, "report.md")

	var out bytes.Buffer
	if err := run(Options{Output: output}, []string{dir}, &out); err != nil {
		t.Fatalf("run returned an error: %v", err)
	}

	report, err := os.ReadFile(output)
	if err != nil {
		t.Fatal(err)
	}
	got := string(report)
	if !strings.HasPrefix(got, "# Lint findings\n\n<!-- Generated by: phpscript lint -o ") {
		t.Errorf("report is missing its header:\n%s", got)
	}
	if !strings.Contains(got, out.String()) {
		t.Errorf("report does not contain the stdout table:\n%s\nwant:\n%s", got, out.String())
	}
}

func TestRunReportsAnsiTableOnATerminal(t *testing.T) {
	dir := t.TempDir()
	writeLintFile(t, dir, "warn.php", `<?php if ($value = true) {}`)

	// A pipe is not a terminal, so this builds the table directly to check
	// what a terminal would show.
	var buf bytes.Buffer
	tbl := newTable(&buf, false, "src")
	tbl.Row(table.Colored(statusColor(statusWarn), statusWarn), table.Text("warn.php"), table.Text("1"), table.Text("finding"))
	tbl.Flush()

	got := buf.String()
	for _, want := range []string{table.BoxTopLeft, table.ColorHeader + "Status", table.ColorAmber + "WARN"} {
		if !strings.Contains(got, want) {
			t.Errorf("table does not contain %q:\n%q", want, got)
		}
	}
}

// TestNewCommand covers the two flags this command owns and the shared one it
// reads. --flatstack and -o are its own; --include is global, and the Run
// closure copies it into the options at call time, because main fills the
// global options from the configuration past the command's construction.
func TestNewCommand(t *testing.T) {
	command := NewCommand(nil, &flags.Options{})

	if command.Name != "lint" {
		t.Errorf("Name = %q, want %q", command.Name, "lint")
	}
	if command.Title != Name {
		t.Errorf("Title = %q, want %q", command.Title, Name)
	}
	if command.Bind == nil {
		t.Fatal("Bind is nil, want --flatstack and --output")
	}

	set := helpdocs.NewFlagSet("lint")
	command.Bind(set)
	for _, test := range []struct {
		name      string
		shorthand string
		value     string
	}{
		{name: "flatstack", value: "false"},
		{name: "output", shorthand: "o", value: ""},
	} {
		flag := set.Lookup(test.name)
		if flag == nil {
			t.Errorf("--%s is not bound", test.name)
			continue
		}
		if flag.Shorthand != test.shorthand {
			t.Errorf("--%s shorthand = %q, want %q", test.name, flag.Shorthand, test.shorthand)
		}
		if flag.DefValue != test.value {
			t.Errorf("--%s default = %q, want %q", test.name, flag.DefValue, test.value)
		}
	}
}

// TestRun covers the exported entry point: run() pointed at stdout.
// A folder holding one failing file fails the command, because a parse error
// is a finding the run cannot report around; the table is still printed, so
// the operator reads what failed and not only that something did.
func TestRun(t *testing.T) {
	dir := t.TempDir()
	writeLintFile(t, dir, "fail.php", `<?php class Foo {`)

	out := captureStdout(t, func() {
		if err := Run(Options{}, []string{dir}); err == nil {
			t.Error("Run = nil over a file that does not parse, want the failure count")
		}
	})

	got := collapse(out)
	if !strings.Contains(got, "| FAIL | fail.php | 1 | parse error:") {
		t.Errorf("stdout does not carry the failing row:\n%s", out)
	}
	if !strings.Contains(got, "Passing 0, with 0 warnings, 1 failing") {
		t.Errorf("stdout does not carry the summary:\n%s", out)
	}
}

// captureStdout runs fn with os.Stdout on a pipe and returns what it wrote.
// Run picks os.Stdout itself, so the file descriptor is the only place to
// read its output from.
func captureStdout(t *testing.T, fn func()) string {
	t.Helper()

	saved := os.Stdout
	reader, writer, err := os.Pipe()
	if err != nil {
		t.Fatal(err)
	}
	os.Stdout = writer
	fn()
	writer.Close()
	os.Stdout = saved

	var buf bytes.Buffer
	if _, err := io.Copy(&buf, reader); err != nil {
		t.Fatal(err)
	}
	return buf.String()
}

// collapse squeezes the runs of padding a table adds, so an assertion names
// the cells of a row and not their column widths.
func collapse(value string) string {
	return strings.Join(strings.Fields(value), " ")
}

func writeLintFile(t *testing.T, dir, name, src string) {
	t.Helper()
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, name), []byte(src), 0o644); err != nil {
		t.Fatal(err)
	}
}
