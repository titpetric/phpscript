// TestReportArgs covers the invocation the provenance comment names. It is
// derived from the options the run was given rather than hardcoded, so the
// committed report says which job wrote it and a reader can run the same
// command. The flags come out in one order, so a regenerated report differs
// only where a result differs.
func TestReportArgs(t *testing.T) {
	if got := strings.Join(reportArgs(Options{}, nil), " "); got != "test" {
		t.Errorf("a bare run reconstructs as %q, want \"test\"", got)
	}

	opts := Options{
		Include:  filepath.Join("tests", "prelude.php"),
		Matrix:   true,
		SkipPHP:  true,
		Verbose:  true,
		Profile:  true,
		Parallel: 4,
		Output:   filepath.Join("docs", "test-fixtures.md"),
	}
	want := "test --include tests/prelude.php --matrix --skip-php -v --profile --parallel 4 -o docs/test-fixtures.md ./..."
	if got := strings.Join(reportArgs(opts, []string{"./..."}), " "); got != want {
		t.Errorf("reportArgs = %q, want %q", got, want)
	}

	// A parallelism of one is the default and says nothing, so a report taken
	// without the flag does not claim it.
	if got := strings.Join(reportArgs(Options{Parallel: 1}, nil), " "); got != "test" {
		t.Errorf("--parallel 1 reconstructs as %q, want \"test\"", got)
	}
}

// TestWriteReportHeader covers the opening of a generated report: the title,
// the command that produced it, and the sentence saying a table below is a
// compatibility report and no record of what phpscript last printed.
func TestWriteReportHeader(t *testing.T) {
	var buf bytes.Buffer
	writeReportHeader(&buf, reportArgs(Options{Matrix: true}, []string{"./..."}))

	got := buf.String()
	for _, want := range []string{
		"# Test fixtures\n",
		"<!-- Generated by: phpscript test --matrix ./... -->",
		"compatibility report",
		"testing.md",
	} {
		if !strings.Contains(got, want) {
			t.Errorf("the header is missing %q:\n%s", want, got)
		}
	}
	if !strings.HasPrefix(got, "# Test fixtures") {
		t.Errorf("the header does not open on the title:\n%s", got)
	}
}

// TestOpenReport covers when the -o sink is created, which is before the first
// fixture runs: an unwritable path fails the command immediately and not after
// the whole suite executed. A run naming no output opens nothing, so the
// terminal table is the only sink.
func TestOpenReport(t *testing.T) {
	if file, err := openReport(Options{}, nil); err != nil || file != nil {
		t.Errorf("openReport with no --output = %v, %v, want no file and no error", file, err)
	}

	path := filepath.Join(t.TempDir(), "report.md")
	file, err := openReport(Options{Output: path}, []string{"./..."})
	if err != nil {
		t.Fatalf("openReport: %v", err)
	}
	if file == nil {
		t.Fatal("openReport answered no file for a named output")
	}
	if err := file.Close(); err != nil {
		t.Fatal(err)
	}

	written, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(written), "# Test fixtures") {
		t.Errorf("the header was not written at open:\n%s", written)
	}

	if _, err := openReport(Options{Output: filepath.Join(path, "nested.md")}, nil); err == nil {
		t.Error("openReport accepted a path under a file, want the run to fail at once")
	}
}

// TestTeeResultTable covers the fan-out that lets one run print a terminal
// table and write a markdown report at the same time. Every call reaches every
// sink, so the two documents report the same run.
func TestTeeResultTable(t *testing.T) {
	var terminal, markdown bytes.Buffer
	sinks := teeResultTable{newMarkdownTable(&terminal, Options{}), newMarkdownTable(&markdown, Options{})}

	sinks.writeGroup("arrays", []string{"a.phpt"})
	sinks.writeResult(&fixtureRun{Result: &tests.TestResult{Passed: true}, Label: "a.phpt"})
	sinks.closeGroup(groupTotals{Dir: "arrays", Passed: 1, Total: 1})
	sinks.writeSummary(1, 0, 1, time.Millisecond)

	if terminal.String() == "" {
		t.Fatal("the first sink received nothing")
	}
	if terminal.String() != markdown.String() {
		t.Errorf("the sinks disagree:\n%s\nagainst:\n%s", terminal.String(), markdown.String())
	}

	// A tee of nothing is the shape a run with no sink at all takes, and every
	// call has to be a no-op rather than a nil dereference.
	empty := teeResultTable{}
	empty.writeGroup("arrays", nil)
	empty.writeResult(&fixtureRun{Result: &tests.TestResult{Passed: true}})
	empty.closeGroup(groupTotals{})
	empty.writeSummary(0, 0, 0, 0)
}

// TestTeeMatrixTable is the same fan-out for the cross-runner matrix.
func TestTeeMatrixTable(t *testing.T) {
	var first, second bytes.Buffer
	sinks := teeMatrixTable{newMarkdownMatrix(&first, Options{}), newMarkdownMatrix(&second, Options{})}

	row := matrixRow{
		DisplayPath: "arrays/a.phpt",
		Label:       "a.phpt",
		Cells:       []matrixCell{{Runner: tests.RunnerRuntime, Status: matrixPass}},
	}
	sinks.writeGroup("arrays", []string{"a.phpt"})
	sinks.writeRow(row)
	sinks.closeGroup(groupTotals{Dir: "arrays", Passed: 1, Total: 1})
	sinks.writeSummary(1, 0, 1, time.Millisecond, nil)

	if first.String() == "" {
		t.Fatal("the first sink received nothing")
	}
	if first.String() != second.String() {
		t.Errorf("the sinks disagree:\n%s\nagainst:\n%s", first.String(), second.String())
	}

	empty := teeMatrixTable{}
	empty.writeGroup("arrays", nil)
	empty.writeRow(row)
	empty.closeGroup(groupTotals{})
	empty.writeSummary(0, 0, 0, 0, nil)
}
