// teeResultTable forwards every call to each table, so one run prints a
// terminal table to stdout and writes a markdown report to a file.
type teeResultTable []resultTable

func (t teeResultTable) writeGroup(dir string, labels []string) {
	for _, table := range t {
		table.writeGroup(dir, labels)
	}
}

func (t teeResultTable) writeResult(r *fixtureRun) {
	for _, table := range t {
		table.writeResult(r)
	}
}

func (t teeResultTable) closeGroup(totals groupTotals) {
	for _, table := range t {
		table.closeGroup(totals)
	}
}

func (t teeResultTable) writeSummary(passed, failed, total int, duration time.Duration) {
	for _, table := range t {
		table.writeSummary(passed, failed, total, duration)
	}
}

